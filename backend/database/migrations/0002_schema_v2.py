def _functions(db) -> None:
    db.execute("""
        CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            NEW.updated_at := now();
            RETURN NEW;
        END $$""")
    db.execute("""
        CREATE FUNCTION forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION '% jadvali faqat yoziladi: % taqiqlangan',
                TG_TABLE_NAME, TG_OP;
        END $$""")


def _updated_at(db, table: str) -> None:
    db.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS updated_at "
               f"TIMESTAMPTZ NOT NULL DEFAULT now()")
    db.execute(f"CREATE TRIGGER {table}_updated_at BEFORE UPDATE ON {table} "
               f"FOR EACH ROW EXECUTE FUNCTION set_updated_at()")


