def _devices(db) -> None:
    db.execute("""
        CREATE TABLE devices (
            id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
            kind            TEXT NOT NULL DEFAULT 'camera' CHECK (kind IN ('camera', 'nvr')),
            vendor          TEXT NOT NULL DEFAULT 'boshqa' CHECK (btrim(vendor) <> ''),
            -- IP yoki DNS nomi (DDNS orqali ulanadigan registratorlar uchun
            -- INET emas): faqat manzilga xos belgilar.
            host            TEXT NOT NULL CHECK (host ~ '^[A-Za-z0-9][A-Za-z0-9.:-]*$'),
            rtsp_port       INTEGER NOT NULL DEFAULT 554 CHECK (rtsp_port BETWEEN 1 AND 65535),
            username        TEXT CHECK (username IS NULL OR username <> ''),
            -- Fernet bilan shifrlangan; kalit DATA_DIR/secret.key da, bazada EMAS.
            password_enc    TEXT CHECK (password_enc IS NULL OR password_enc <> ''),
            model           TEXT CHECK (model IS NULL OR model <> ''),
            firmware        TEXT CHECK (firmware IS NULL OR firmware <> ''),
            created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
            UNIQUE (organization_id, host, rtsp_port)
        )""")
    _updated_at(db, "devices")
    # Har bir IP:port — bitta qurilma. Login/parol, model va firmware eng
    # kichik id'li kameradan olinadi (bir qurilmaning kanallarida bir xil).
    db.execute("""
        INSERT INTO devices (organization_id, kind, vendor, host, rtsp_port,
                             username, password_enc, model, firmware)
        SELECT %s,
               CASE WHEN g.n > 1 THEN 'nvr' ELSE 'camera' END,
               COALESCE(NULLIF(c.vendor, ''), 'boshqa'), c.ip, c.port,
               NULLIF(c.username, ''), NULLIF(c.password_enc, ''),
               NULLIF(c.model, ''), NULLIF(c.firmware, '')
        FROM (SELECT ip, port, MIN(id) AS first_id, COUNT(*) AS n
              FROM cameras WHERE ip IS NOT NULL AND ip <> ''
              GROUP BY ip, port) g
        JOIN cameras c ON c.id = g.first_id
        ORDER BY g.first_id""", (DEFAULT_ORGANIZATION_ID,))


def _cameras(db, area_ids: dict[str, int], rail_line_id: int) -> None:
    c = "ALTER TABLE cameras "
    db.execute(c + "ADD COLUMN organization_id INTEGER")
    db.execute(c + "ADD COLUMN device_id INTEGER")
    db.execute(c + "ADD COLUMN source_type TEXT")
    db.execute(c + "ADD COLUMN admin_area_id INTEGER")
    db.execute(c + "ADD COLUMN rail_line_id INTEGER")
    db.execute(c + "ADD COLUMN km INTEGER")
    db.execute(c + "ADD COLUMN picket SMALLINT")
    db.execute(c + "ADD COLUMN rail_unit_id INTEGER")
    db.execute(c + "ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now()")

    db.execute("UPDATE cameras SET organization_id = %s", (DEFAULT_ORGANIZATION_ID,))
    db.execute("UPDATE cameras c SET device_id = d.id FROM devices d "
               "WHERE d.host = c.ip AND d.rtsp_port = c.port")
    db.execute("UPDATE cameras SET source_type = "
               "CASE WHEN device_id IS NOT NULL THEN 'rtsp' ELSE 'manual' END")

    # Jonli holat alohida jadvalga.
    db.execute("""
        CREATE TABLE camera_status (
            camera_id   INTEGER PRIMARY KEY REFERENCES cameras(id) ON DELETE CASCADE,
            codec       TEXT CHECK (codec IS NULL OR codec <> ''),
            sub_codec   TEXT CHECK (sub_codec IS NULL OR sub_codec <> ''),
            resolution  TEXT CHECK (resolution IS NULL OR resolution <> ''),
            fps         REAL CHECK (fps IS NULL OR fps > 0),
            -- Kodek brauzerda o'ynalmaydi (H.265) — H.264 ga o'giriladi.
            transcode   BOOLEAN NOT NULL DEFAULT false,
            -- Sub oqimi brauzerda ochilmagan: devor asosiy oqimdan ochadi.
            sub_bad     BOOLEAN NOT NULL DEFAULT false,
            -- Kamera RTSP'ni TCP orqali bermaydi — UDP kerak.
            rtsp_udp    BOOLEAN NOT NULL DEFAULT false,
            last_seen   TIMESTAMPTZ,
            snapshot_at TIMESTAMPTZ
        )""")
    _updated_at(db, "camera_status")
    db.execute("""
        INSERT INTO camera_status (camera_id, codec, sub_codec, resolution, fps,
                                   transcode, sub_bad, rtsp_udp, last_seen, snapshot_at)
        SELECT id, NULLIF(codec, ''), NULLIF(sub_codec, ''), NULLIF(resolution, ''),
               NULLIF(fps, 0), transcode = 1, sub_bad = 1, rtsp_udp = 1,
               last_seen, snapshot_at
        FROM cameras""")

    # "Yo'q" — faqat NULL. 0,0 — Gvineya ko'rfazidagi haqiqiy nuqta.
    db.execute(c + "ALTER COLUMN lat DROP NOT NULL")
    db.execute(c + "ALTER COLUMN lng DROP NOT NULL")
    db.execute("UPDATE cameras SET lat = NULL, lng = NULL WHERE lat = 0 AND lng = 0")
    db.execute(c + "ALTER COLUMN stream_url DROP NOT NULL")
    db.execute(c + "ALTER COLUMN stream_url DROP DEFAULT")
    for col in ("stream_url", "rtsp_path", "sub_path", "note", "external_id"):
        db.execute(f"UPDATE cameras SET {col} = NULL WHERE btrim({col}) = ''")

    # Hudud: avval koordinata bo'yicha (viloyat chegarasi), bo'lmasa eski
    # matn viloyat nomiga aynan mos kelsa. "Toshkent" kabi noaniq matn
    # taxmin qilinmaydi — NULL ("belgilanmagan") qoladi.
    boundaries = [(r[0], r[1]) for r in db.execute(
        "SELECT id, boundary FROM admin_areas WHERE level = 'region'")]
    lower = {k.lower(): v for k, v in area_ids.items()}
    for cam_id, lat, lng, region, name in db.execute(
            "SELECT id, lat, lng, region, name FROM cameras").fetchall():
        area = None
        if lat is not None and lng is not None:
            area = next((aid for aid, geom in boundaries
                         if point_in_geometry(lng, lat, geom)), None)
        if area is None:
            area = lower.get((region or "").strip().lower())
        m = _KM_PIKET.match(name or "")
        db.execute(
            "UPDATE cameras SET admin_area_id = %s, rail_line_id = %s, km = %s, "
            "picket = %s WHERE id = %s",
            (area, rail_line_id if m else None,
             int(m.group(1)) if m else None, int(m.group(2)) if m else None, cam_id))

    _to_bool(db, "cameras", "enabled", True)
    _to_bool(db, "cameras", "always_on", False)
    db.execute(c + "RENAME COLUMN node_id TO media_node_id")
    db.execute("ALTER INDEX idx_cameras_node RENAME TO idx_cameras_media_node")

    for col in ("region", "ip", "port", "username", "password_enc", "vendor",
                "model", "firmware", "codec", "sub_codec", "resolution", "fps",
                "transcode", "sub_bad", "rtsp_udp", "last_seen", "snapshot_at"):
        db.execute(c + f"DROP COLUMN {col}")
    db.execute("DROP INDEX IF EXISTS idx_cameras_external")

    for col in ("organization_id", "source_type"):
        db.execute(c + f"ALTER COLUMN {col} SET NOT NULL")
    db.execute(c + "ADD CONSTRAINT cameras_organization_fk FOREIGN KEY (organization_id) "
               "REFERENCES organizations(id) ON DELETE RESTRICT")
    db.execute(c + "ADD CONSTRAINT cameras_device_fk FOREIGN KEY (device_id) "
               "REFERENCES devices(id) ON DELETE RESTRICT")
    db.execute(c + "ADD CONSTRAINT cameras_admin_area_fk FOREIGN KEY (admin_area_id) "
               "REFERENCES admin_areas(id) ON DELETE SET NULL")
    db.execute(c + "ADD CONSTRAINT cameras_rail_line_fk FOREIGN KEY (rail_line_id) "
               "REFERENCES rail_lines(id) ON DELETE RESTRICT")
    db.execute(c + "ADD CONSTRAINT cameras_rail_unit_fk FOREIGN KEY (rail_unit_id) "
               "REFERENCES rail_units(id) ON DELETE SET NULL")
    checks = {
        "cameras_source_check":
            "(source_type = 'rtsp' AND device_id IS NOT NULL AND rtsp_path IS NOT NULL) "
            "OR (source_type = 'manual' AND device_id IS NULL AND stream_url IS NOT NULL)",
        "cameras_name_check": "btrim(name) <> ''",
        "cameras_location_check": "(lat IS NULL) = (lng IS NULL)",
        # km faqat yo'nalish bilan; piket faqat km bilan.
        "cameras_km_check": "(km IS NULL) = (rail_line_id IS NULL) AND (km IS NULL OR km >= 0)",
        "cameras_picket_check": "picket IS NULL OR (km IS NOT NULL AND picket BETWEEN 1 AND 10)",
        # Bo'sh satr taqiqlanadi ("yo'q" — NULL). NULL'da ifoda NULL bo'ladi
        # va CHECK o'tadi; '' da FALSE — rad etiladi.
        "cameras_empty_check":
            "stream_url <> '' AND rtsp_path <> '' AND sub_path <> '' "
            "AND note <> '' AND external_id <> ''",
    }
    for name, expr in checks.items():
        db.execute(c + f"ADD CONSTRAINT {name} CHECK ({expr})")
    db.execute(c + "ADD CONSTRAINT cameras_device_path_key UNIQUE (device_id, rtsp_path)")
    db.execute(c + "ADD CONSTRAINT cameras_external_key UNIQUE (organization_id, external_id)")
    for idx, cols in (("organization", "organization_id"), ("device", "device_id"),
                      ("admin_area", "admin_area_id"), ("rail_unit", "rail_unit_id"),
                      ("rail_km", "rail_line_id, km")):
        db.execute(f"CREATE INDEX idx_cameras_{idx} ON cameras({cols})")
    _updated_at(db, "cameras")


def _history(db) -> None:
    # events -> camera_events: kamera id bilan. Oqim yo'li (path) ham
    # saqlanadi — muzlash asosiy, sub yoki o'girilgan yo'lda bo'lishi mumkin.
    db.execute("ALTER TABLE events RENAME TO camera_events")
    db.execute("ALTER TABLE camera_events RENAME COLUMN slug TO path")
    db.execute("ALTER TABLE camera_events ADD COLUMN camera_id INTEGER "
               "REFERENCES cameras(id) ON DELETE CASCADE")
    db.execute("UPDATE camera_events e SET camera_id = c.id FROM cameras c "
               "WHERE c.slug = regexp_replace(e.path, '_(sub|h264)$', '')")
    db.execute("ALTER TABLE camera_events DROP COLUMN ip")
    db.execute("ALTER TABLE camera_events DROP COLUMN port")
    db.execute("UPDATE camera_events SET detail = NULL WHERE btrim(detail) = ''")
    db.execute("ALTER TABLE camera_events ADD CONSTRAINT camera_events_kind_check CHECK "
               "(kind IN ('online', 'offline', 'stalled', 'resumed', 'mediamtx', 'transport'))")
    db.execute("ALTER INDEX idx_events_ts RENAME TO idx_camera_events_ts")
    db.execute("DROP INDEX idx_events_slug_ts")
    db.execute("CREATE INDEX idx_camera_events_camera_ts ON camera_events(camera_id, ts)")

    db.execute("""
        CREATE TABLE status_changes (
            id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ts        TIMESTAMPTZ NOT NULL,
            camera_id INTEGER NOT NULL REFERENCES cameras(id) ON DELETE CASCADE,
            kind      TEXT NOT NULL CHECK (kind IN ('online', 'offline'))
        )""")
    db.execute("INSERT INTO status_changes (ts, camera_id, kind) "
               "SELECT s.ts, s.camera_id, s.kind FROM stats_event s "
               "JOIN cameras c ON c.id = s.camera_id ORDER BY s.id")
    db.execute("DROP TABLE stats_event")
    db.execute("CREATE INDEX idx_status_changes_ts ON status_changes(ts)")
    db.execute("CREATE INDEX idx_status_changes_camera ON status_changes(camera_id)")

    db.execute("""
        CREATE TABLE availability_snapshots (
            ts              TIMESTAMPTZ NOT NULL,
            organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
            admin_area_id   INTEGER REFERENCES admin_areas(id) ON DELETE CASCADE,
            total           INTEGER NOT NULL CHECK (total >= 0),
            online          INTEGER NOT NULL CHECK (online BETWEEN 0 AND total),
            UNIQUE NULLS NOT DISTINCT (ts, organization_id, admin_area_id)
        )""")
    # Eski "3428 km" kesimi hudud emas — bir vaqtdagi qatorlar
    # "belgilanmagan" (NULL) hududga yig'iladi; aniq viloyat nomlari saqlanadi.
    db.execute("""
        INSERT INTO availability_snapshots (ts, organization_id, admin_area_id, total, online)
        SELECT s.ts, %s, a.id, SUM(s.total), SUM(s.online)
        FROM stats_region s
        LEFT JOIN admin_areas a ON lower(a.name) = lower(s.region) AND a.level = 'region'
        GROUP BY s.ts, a.id""", (DEFAULT_ORGANIZATION_ID,))
    db.execute("DROP TABLE stats_region")
    db.execute("CREATE INDEX idx_availability_ts ON availability_snapshots(ts)")


