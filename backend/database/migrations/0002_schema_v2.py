def _drop_checks(db, table: str, column: str) -> None:
    """Ustunga tegishli CHECK cheklovlarini olib tashlaydi (tip o'zgarishidan oldin)."""
    rows = db.execute(
        "SELECT con.conname FROM pg_constraint con "
        "JOIN pg_attribute att ON att.attrelid = con.conrelid "
        "  AND att.attnum = ANY(con.conkey) "
        "WHERE con.contype = 'c' AND con.conrelid = %s::regclass "
        "  AND att.attname = %s", (table, column)).fetchall()
    for (name,) in rows:
        db.execute(f'ALTER TABLE {table} DROP CONSTRAINT "{name}"')


def _to_bool(db, table: str, column: str, default: bool) -> None:
    _drop_checks(db, table, column)
    db.execute(f"ALTER TABLE {table} ALTER COLUMN {column} DROP DEFAULT")
    db.execute(f"ALTER TABLE {table} ALTER COLUMN {column} TYPE BOOLEAN "
               f"USING {column} = 1")
    db.execute(f"ALTER TABLE {table} ALTER COLUMN {column} "
               f"SET DEFAULT {'true' if default else 'false'}")


def _point_in_ring(lng: float, lat: float, ring: list) -> bool:
    inside = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > lat) != (yj > lat) and \
                lng < (xj - xi) * (lat - yi) / ((yj - yi) or 1e-12) + xi:
            inside = not inside
        j = i
    return inside


def point_in_geometry(lng: float, lat: float, geom: dict) -> bool:
    """GeoJSON Polygon/MultiPolygon ichidami (teshiklar hisobga olinadi)."""
    polygons = ([geom["coordinates"]] if geom["type"] == "Polygon"
                else geom["coordinates"] if geom["type"] == "MultiPolygon" else [])
    for rings in polygons:
        if rings and _point_in_ring(lng, lat, rings[0]) and \
                not any(_point_in_ring(lng, lat, hole) for hole in rings[1:]):
            return True
    return False


