def _admin_areas(db) -> dict[str, int]:
    db.execute("""
        CREATE TABLE admin_areas (
            id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id  INTEGER REFERENCES admin_areas(id) ON DELETE RESTRICT,
            level      TEXT NOT NULL CHECK (level IN ('region', 'district')),
            name       TEXT NOT NULL CHECK (btrim(name) <> ''),
            soato_code TEXT UNIQUE,
            -- GeoJSON geometriya (Polygon/MultiPolygon). PostGIS qo'shilganda
            -- geography ustuniga aylantiriladi.
            boundary   JSONB,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK ((level = 'region') = (parent_id IS NULL)),
            UNIQUE NULLS NOT DISTINCT (parent_id, name)
        )""")
    _updated_at(db, "admin_areas")
    db.execute("CREATE INDEX idx_admin_areas_parent ON admin_areas(parent_id)")
    ids: dict[str, int] = {}
    if REGIONS_GEOJSON.exists():
        data = json.loads(REGIONS_GEOJSON.read_text(encoding="utf-8"))
        for feature in data["features"]:
            name = feature["properties"]["name"]
            ids[name] = db.execute(
                "INSERT INTO admin_areas (level, name, boundary) "
                "VALUES ('region', %s, %s) RETURNING id",
                (name, json.dumps(feature["geometry"]))).fetchone()[0]
    return ids


def _rail(db) -> int:
    db.execute("""
        CREATE TABLE rail_lines (
            id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code       TEXT NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_-]+$'),
            name       TEXT NOT NULL CHECK (btrim(name) <> ''),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )""")
    _updated_at(db, "rail_lines")
    db.execute("""
        CREATE TABLE rail_units (
            id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id    INTEGER REFERENCES rail_units(id) ON DELETE RESTRICT,
            rail_line_id INTEGER REFERENCES rail_lines(id) ON DELETE RESTRICT,
            kind         TEXT NOT NULL CHECK (kind IN ('division', 'station', 'stage')),
            name         TEXT NOT NULL CHECK (btrim(name) <> ''),
            code         TEXT UNIQUE,
            km_start     INTEGER CHECK (km_start >= 0),
            km_end       INTEGER,
            created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
            CHECK (km_end IS NULL OR km_start IS NULL OR km_end >= km_start),
            -- km oralig'i faqat yo'nalish ko'rsatilganda ma'noli.
            CHECK (km_start IS NULL OR rail_line_id IS NOT NULL),
            UNIQUE NULLS NOT DISTINCT (parent_id, name)
        )""")
    _updated_at(db, "rail_units")
    db.execute("CREATE INDEX idx_rail_units_parent ON rail_units(parent_id)")
    db.execute("CREATE INDEX idx_rail_units_km ON rail_units(rail_line_id, km_start, km_end)")
    # Hozirgi kameralar bitta yo'nalishda (3372-3718 km). Haqiqiy nomi
    # yo'nalishlar ro'yxati kelganda yangilanadi.
    return db.execute("INSERT INTO rail_lines (code, name) "
                      "VALUES ('main', 'Asosiy yo''nalish') RETURNING id").fetchone()[0]


