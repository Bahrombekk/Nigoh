def _audit(db) -> None:
    db.execute("""
        CREATE TABLE audit_log (
            id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            ts              TIMESTAMPTZ NOT NULL DEFAULT now(),
            organization_id INTEGER REFERENCES organizations(id) ON DELETE SET NULL,
            user_id         INTEGER REFERENCES users(id) ON DELETE SET NULL,
            -- Kim: login yoki "api-key" — foydalanuvchi o'chirilsa ham qoladi.
            actor           TEXT NOT NULL,
            action          TEXT NOT NULL CHECK (action ~ '^[a-z_.]+$'),
            entity          TEXT NOT NULL,
            entity_id       TEXT,
            before          JSONB,
            after           JSONB,
            ip              TEXT
        )""")
    db.execute("CREATE INDEX idx_audit_log_ts ON audit_log(ts)")
    db.execute("CREATE INDEX idx_audit_log_entity ON audit_log(entity, entity_id)")
    db.execute("CREATE TRIGGER audit_log_immutable BEFORE UPDATE OR DELETE ON audit_log "
               "FOR EACH ROW EXECUTE FUNCTION forbid_change()")
    db.execute("CREATE TRIGGER audit_log_no_truncate BEFORE TRUNCATE ON audit_log "
               "FOR EACH STATEMENT EXECUTE FUNCTION forbid_change()")


def _view(db) -> None:
    """Kamera haqidagi hamma narsa bitta tekis qatorda — o'qish uchun.

    Yozish har doim asl jadvallarga (cameras, devices, camera_status)
    database/cameras.py orqali. Ustun nomlari API javoblari bilan bir xil.
    """
    db.execute("""
        CREATE VIEW camera_details AS
        SELECT c.id, c.organization_id, c.name, c.slug, c.source_type,
               c.lat, c.lng,
               c.admin_area_id, COALESCE(a.name, 'Belgilanmagan') AS region,
               c.rail_line_id, c.km, c.picket, c.rail_unit_id,
               c.stream_url, c.device_id,
               d.host AS ip, d.rtsp_port AS port, d.username, d.password_enc,
               COALESCE(d.vendor, 'boshqa') AS vendor, d.model, d.firmware,
               d.kind AS device_kind,
               c.rtsp_path, c.sub_path, c.media_node_id AS node_id,
               c.enabled, c.always_on, c.note, c.external_id,
               c.created_at, c.updated_at,
               s.codec, s.sub_codec, s.resolution, s.fps, s.transcode,
               s.sub_bad, s.rtsp_udp, s.last_seen, s.snapshot_at
        FROM cameras c
        LEFT JOIN devices d ON d.id = c.device_id
        LEFT JOIN camera_status s ON s.camera_id = c.id
        LEFT JOIN admin_areas a ON a.id = c.admin_area_id""")


