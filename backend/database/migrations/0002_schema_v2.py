def _verify(db, before: dict[str, int]) -> None:
    """Ko'chishdan keyin sonlar mos kelmasa — butun tranzaksiya bekor."""
    after = {
        "cameras": db.execute("SELECT COUNT(*) FROM cameras").fetchone()[0],
        "camera_status": db.execute("SELECT COUNT(*) FROM camera_status").fetchone()[0],
        "camera_events": db.execute("SELECT COUNT(*) FROM camera_events").fetchone()[0],
        "users": db.execute("SELECT COUNT(*) FROM users").fetchone()[0],
    }
    expected = {"cameras": before["cameras"], "camera_status": before["cameras"],
                "camera_events": before["events"], "users": before["admins"]}
    if after != expected:
        raise RuntimeError(f"2-migratsiya: sonlar mos emas {after} != {expected}")
    orphans = db.execute("SELECT COUNT(*) FROM cameras WHERE source_type = 'rtsp' "
                         "AND device_id IS NULL").fetchone()[0]
    if orphans:
        raise RuntimeError(f"2-migratsiya: {orphans} ta kamera qurilmasiz qoldi")


